// Pure JSON extraction: find the first balanced {...} object in free text.

/**
 * Extract the first balanced JSON object from text (e.g. an LLM reply
 * wrapped in prose or a fenced code block). Returns undefined when no
 * balanced object exists. String-aware: braces inside "..." don't count.
 */
export function extractJsonObject(text: string): string | undefined {
  const start = text.indexOf("{");
  if (start < 0) return undefined;
  let depth = 0;
  let inString = false;
  let escaped = false;
  for (let i = start; i < text.length; i++) {
    const ch = text[i]!;
    if (inString) {
      if (escaped) escaped = false;
      else if (ch === "\\") escaped = true;
      else if (ch === '"') inString = false;
      continue;
    }
    if (ch === '"') inString = true;
    else if (ch === "{") depth++;
    else if (ch === "}") {
      depth--;
      if (depth === 0) return text.slice(start, i + 1);
    }
  }
  return undefined;
}
