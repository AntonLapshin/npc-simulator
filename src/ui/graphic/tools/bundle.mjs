#!/usr/bin/env node
// tools/bundle.mjs — build a self-contained preview.html from the modular
// sources: CSS inlined into <style>, ES modules concatenated into a single
// classic <script> (import/export statements stripped, dependency order
// computed from the import graph).
//
// This exists so the UI can be previewed in contexts without a module
// server (e.g. sandboxed iframe viewers or a plain double-click open).
// The canonical entry point stays index.html + js/**.
//
// Usage: node tools/bundle.mjs [--out preview.html]

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ENTRY = "js/main.js";
const CSS_FILES = [
  "styles/base.css",
  "styles/layout.css",
  "styles/stage.css",
  "styles/panels.css",
  "styles/composer.css",
];

/** Collect the import graph and return module paths in dependency order. */
async function topoOrder(entry) {
  const order = [];
  const seen = new Set();
  async function visit(path) {
    if (seen.has(path)) return;
    seen.add(path);
    const src = await readFile(join(ROOT, path), "utf-8");
    const re = /import\s+[^;"']*?from\s*["']([^"']+)["']/g;
    let m;
    while ((m = re.exec(src))) {
      const dep = m[1];
      if (!dep.startsWith(".")) continue;
      await visit(join(dirname(path), dep));
    }
    order.push(path);
  }
  await visit(entry);
  return order;
}

/** Strip ES module syntax so files concatenate into one classic script. */
function stripModuleSyntax(src) {
  return (
    src
      // import … from "…"; (single or multiline) and bare import "…";
      .replace(/^\s*import\s+[^;]*?from\s*["'][^"']+["'];?\s*$/gm, "")
      .replace(/^\s*import\s*["'][^"']+["'];?\s*$/gm, "")
      // export declarations → plain declarations
      .replace(/^(\s*)export\s+(async\s+function|function|class|const|let|var)\b/gm, "$1$2")
      // export { … }; lists (unused in this codebase, kept for safety)
      .replace(/^\s*export\s*\{[^}]*\};?\s*$/gm, "")
  );
}

function detectCollisions(chunks) {
  const decls = new Map();
  for (const { path, code } of chunks) {
    const re = /^(?:const|let|var|function|async function|class)\s+([A-Za-z_$][\w$]*)/gm;
    let m;
    while ((m = re.exec(code))) {
      const name = m[1];
      if (decls.has(name)) {
        console.warn(`[bundle] top-level name collision: '${name}' in ${decls.get(name)} and ${path}`);
      } else {
        decls.set(name, path);
      }
    }
  }
}

async function main() {
  const outIdx = process.argv.indexOf("--out");
  const outFile = outIdx !== -1 ? process.argv[outIdx + 1] : "preview.html";

  const modules = await topoOrder(ENTRY);
  const chunks = [];
  for (const path of modules) {
    const code = stripModuleSyntax(await readFile(join(ROOT, path), "utf-8"));
    chunks.push({ path, code });
  }
  detectCollisions(chunks);

  const css = (await Promise.all(CSS_FILES.map((f) => readFile(join(ROOT, f), "utf-8")))).join("\n\n");
  const js = chunks.map(({ path, code }) => `/* ══ ${path} ══ */\n${code}`).join("\n;\n");
  const body = await bodyMarkup();

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>NPC Simulator — Northlight Studio (bundled preview)</title>
<!-- Generated by tools/bundle.mjs — do not edit. Source of truth: index.html + styles/ + js/ -->
<link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/@fontsource/outfit/400.css">
<link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/@fontsource/outfit/600.css">
<link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/@fontsource/outfit/800.css">
<link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/@fontsource/jetbrains-mono/400.css">
<style>
${css}
</style>
</head>
${body}
<script>
"use strict";
(function(){
${js}
})();
</script>
</body>
</html>
`;
  await writeFile(join(ROOT, outFile), html);
  console.log(`[bundle] wrote ${outFile} (${modules.length} modules, ${(html.length / 1024).toFixed(1)} KB)`);
}

/** Extract the <body>…</body> markup from index.html (single source of DOM). */
async function bodyMarkup() {
  const idx = await readFile(join(ROOT, "index.html"), "utf-8");
  const m = /<body>([\s\S]*?)<script type="module"[\s\S]*?<\/body>/.exec(idx);
  if (!m) throw new Error("Could not extract body markup from index.html");
  return "<body>" + m[1].trim();
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
